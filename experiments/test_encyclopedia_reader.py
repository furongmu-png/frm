# ------------------------------------------------------------------ #
# Test 1: index build
# ------------------------------------------------------------------ #
class TestIndexBuild:
    def test_index_file_created(self, corpus_dir):
        tmp, paths = corpus_dir
        index_dir = tmp / ".index"
        index_path = index_dir / "index.json"
        assert not index_path.exists()  # not built yet
        reader = EncyclopediaReader(paths, block_size=64, index_dir=index_dir, seed=42)
        assert index_path.exists(), "index.json should be created"
        assert reader.n_articles() == 10

    def test_index_reused_on_reload(self, corpus_dir):
        tmp, paths = corpus_dir
        index_dir = tmp / ".index"
        r1 = EncyclopediaReader(paths, block_size=64, index_dir=index_dir, seed=42)
        # Modify the index file mtime to detect reload vs rebuild.
        # Actually, simpler: build once, then create a second reader
        # and check it has the same articles.
        r2 = EncyclopediaReader(paths, block_size=64, index_dir=index_dir, seed=42)
        assert r1.get_article_list() == r2.get_article_list()

    def test_index_schema(self, reader):
        assert reader._index["schema_version"] == "1.0"
        assert reader._index["block_size"] == 64
        assert len(reader._index["files"]) == 2
        assert len(reader._index["articles"]) == 10

    def test_index_offset_excludes_doc_tag(self, reader):
        """The offset should point to the START of the body, not the tag."""
        # Pick an article and check the body at the offset starts with
        # the article's content (NOT with '<doc' or '>').
        titles = reader.get_article_list()
        for title in titles[:3]:
            ok = reader.seek_to_article(title)
            assert ok
            block = reader.read_block()
            # Should NOT contain the <doc tag or the closing > of it.
            assert "<doc" not in block[:10], (
                f"body for {title!r} starts with <doc tag: {block[:20]!r}"
            )
            assert not block.startswith(">"), (
                f"body for {title!r} starts with >: {block[:20]!r}"
            )
            # Should contain the title in the first few blocks.
            full_body = reader._get_current_body()
            assert title.split("_")[0].lower() in full_body.lower()[:200], (
                f"body for {title!r} should mention its topic: {full_body[:100]!r}"
            )


# ------------------------------------------------------------------ #
# Test 2: seek
# ------------------------------------------------------------------ #
class TestSeekToArticle:
    def test_seek_to_known_title(self, reader):
        titles = reader.get_article_list()
        ok = reader.seek_to_article(titles[0])
        assert ok is True
        assert reader.get_title() == titles[0]

    def test_seek_to_unknown_title(self, reader):
        ok = reader.seek_to_article("Nonexistent Article XYZ")
        assert ok is False
        # Title is unchanged (whatever it was before).
        assert reader.get_title() == ""

    def test_seek_to_random_article(self, reader):
        title = reader.seek_to_random_article()
        assert title in reader.get_article_list()
        assert reader.get_title() == title

    def test_seek_to_random_deterministic_with_seed(self, corpus_dir):
        """Same seed -> same random article sequence."""
        tmp, paths = corpus_dir
        index_dir1 = tmp / ".index1"
        index_dir2 = tmp / ".index2"
        r1 = EncyclopediaReader(paths, block_size=64, index_dir=index_dir1, seed=123)
        r2 = EncyclopediaReader(paths, block_size=64, index_dir=index_dir2, seed=123)
        seq1 = [r1.seek_to_random_article() for _ in range(5)]
        seq2 = [r2.seek_to_random_article() for _ in range(5)]
        assert seq1 == seq2

    def test_tell_after_seek(self, reader):
        titles = reader.get_article_list()
        reader.seek_to_article(titles[3])
        article_idx, pos = reader.tell()
        assert article_idx == 3
        assert pos == 0

    def test_seek_to_position(self, reader):
        titles = reader.get_article_list()
        reader.seek_to_article(titles[0])
        reader.seek(article_idx=0, pos_in_article=100)
        _, pos = reader.tell()
        assert pos == 100


# ------------------------------------------------------------------ #
# Test 3: read_block
# ------------------------------------------------------------------ #
class TestReadBlock:
    def test_read_block_returns_block_size_chars(self, reader):
        reader.seek_to_random_article()
        block = reader.read_block()
        assert len(block) == reader.block_size, (
            f"expected {reader.block_size} chars, got {len(block)}"
        )

    def test_read_block_advances_position(self, reader):
        reader.seek_to_random_article()
        _, pos0 = reader.tell()
        reader.read_block()
        _, pos1 = reader.tell()
        assert pos1 == pos0 + reader.block_size

    def test_read_multiple_blocks_are_distinct(self, reader):
        reader.seek_to_random_article()
        blocks = [reader.read_block() for _ in range(5)]
        # At least 2 distinct blocks (the article is long enough).
        assert len(set(blocks)) >= 2

    def test_read_at_end_returns_partial_or_empty(self, reader):
        """If we read past the end, we get a partial (or empty) block."""
        reader.seek_to_random_article()
        # Read a LOT of blocks to reach the end.
        for _ in range(1000):
            reader.read_block()
        # Now we should be at the end.
        assert reader.at_article_end()
        block = reader.read_block()
        assert len(block) == 0

    def test_read_block_then_reseek_resets_position(self, reader):
        reader.seek_to_random_article()
        for _ in range(5):
            reader.read_block()
        _, pos_after_reads = reader.tell()
        assert pos_after_reads > 0
        # Seek to a new article -> position resets to 0.
        titles = reader.get_article_list()
        reader.seek_to_article(titles[-1])
        _, pos = reader.tell()
        assert pos == 0


