# Test 4: article links
# ------------------------------------------------------------------ #
class TestArticleLinks:
    def test_every_article_has_links(self, reader):
        """All synthetic articles should have at least 2 links."""
        titles = reader.get_article_list()
        for title in titles:
            links = reader.get_article_links(title)
            assert len(links) >= 2, (
                f"article {title!r} should have >=2 links, got {len(links)}: {links}"
            )

    def test_links_are_other_articles(self, reader):
        """Links should point to OTHER articles in the corpus."""
        titles = set(reader.get_article_list())
        for title in list(titles)[:3]:
            links = reader.get_article_links(title)
            for link in links:
                assert link in titles, (
                    f"link {link!r} from {title!r} not in corpus"
                )
                assert link != title, (
                    f"article {title!r} should not link to itself"
                )

    def test_links_of_current_article(self, reader):
        """get_article_links() with no arg returns current article's links."""
        reader.seek_to_random_article()
        current = reader.get_title()
        links_no_arg = reader.get_article_links()
        links_arg = reader.get_article_links(current)
        assert links_no_arg == links_arg


