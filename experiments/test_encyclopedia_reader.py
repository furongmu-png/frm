# Test 5: compression
# ------------------------------------------------------------------ #
class TestCompression:
    """Reader should work with .gz and .bz2 files."""

    def _compress_corpus(self, corpus_dir, suffix):
        """Compress each wiki_* file with the given suffix."""
        tmp, paths = corpus_dir
        compressed_paths = []
        for p in paths:
            out_path = p.with_suffix(suffix)
            data = p.read_bytes()
            if suffix == ".gz":
                with gzip.open(out_path, "wb") as f:
                    f.write(data)
            elif suffix == ".bz2":
                with bz2.open(out_path, "wb") as f:
                    f.write(data)
            else:
                raise ValueError(f"unknown suffix: {suffix}")
            compressed_paths.append(out_path)
        return compressed_paths

    def test_gz(self, corpus_dir):
        paths = self._compress_corpus(corpus_dir, ".gz")
        tmp, _ = corpus_dir
        reader = EncyclopediaReader(
            paths, block_size=64, index_dir=tmp / ".index_gz", seed=42,
        )
        assert reader.n_articles() == 10
        reader.seek_to_random_article()
        block = reader.read_block()
        assert len(block) == 64

    def test_bz2(self, corpus_dir):
        paths = self._compress_corpus(corpus_dir, ".bz2")
        tmp, _ = corpus_dir
        reader = EncyclopediaReader(
            paths, block_size=64, index_dir=tmp / ".index_bz2", seed=42,
        )
        assert reader.n_articles() == 10
        reader.seek_to_random_article()
        block = reader.read_block()
        assert len(block) == 64


