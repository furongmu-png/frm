# experiments/test_encyclopedia_reader.py
"""Verification tests for ``EncyclopediaReader`` (Phase J, Task 1).

Five test classes:
  1. ``TestIndexBuild`` — index is built and cached on disk.
  2. ``TestSeekToArticle`` — seek by title, by random, state is correct.
  3. ``TestReadBlock`` — read_block returns the right chars and advances pos.
  4. ``TestArticleLinks`` — link parsing extracts the right targets.
  5. ``TestCompression`` — reader works with .gz and .bz2 files.

The tests use a 10-article synthetic corpus generated by
``make_synthetic_corpus`` — no external Wikipedia dump needed.

Run with:  python -m pytest experiments/test_encyclopedia_reader.py -v
"""

